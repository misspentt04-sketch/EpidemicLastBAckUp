def get_infect_chance(attacker_infect: int, victim_immunity: int) -> float:
    """
    Возвращает шанс заражения (0.0 .. 1.0).
    diff = attacker_infect - victim_immunity
    diff >= 0 → 100%
    diff < 0  → по таблице, |diff|
    Если |diff| > 200 → возвращаем 0.00001 (минимум).
    """
    diff = attacker_infect - victim_immunity
    if diff >= 0:
        return 1.0
    key = abs(diff)
    if key > 200:
        return 0.00001
    return INFECT_CHANCE.get(key, 0.00001)
